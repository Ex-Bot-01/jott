// The tree's rows: which entries are visible, how deep they sit, and what the §9 marker says. Kept out
// of Tree.svelte so the marker legend — the part most likely to be quietly wrong — has tests.

import { describe, expect, it } from 'vitest'
import { GENERATED_TITLE, flattenTree, notesAwaitingIndex } from './tree'
import type { NodeEntry } from './ipc'

function entry(rel: string, over: Partial<NodeEntry> = {}): NodeEntry {
  return { rel, kind: 'Note', size: 12, mtimeMs: 1_700_000_000_000, state: 'Waiting', ...over }
}

// In the order the walk returns them: sorted by the bytes of `rel` (Task 7), which is why capital
// `INDEX.md` and lowercase `archive.zip` come before a folder named `inbox`.
const nodes: NodeEntry[] = [
  entry('INDEX.md', { kind: 'Generated', state: null }),
  entry('archive.zip', { kind: 'Attachment', state: null }),
  entry('inbox', { kind: 'Folder', state: null }),
  entry('inbox/idea.md'),
  entry('photo.png', { kind: 'Image', state: null }),
  entry('projects', { kind: 'Folder', state: null }),
  entry('projects/2026', { kind: 'Folder', state: null }),
  entry('projects/2026/q2-review.md', { state: 'Indexed' }),
  entry('timeline.md', { state: 'Embedded' }),
]

describe('flattenTree', () => {
  it('shows top level with nothing open, and root folders only', () => {
    const rows = flattenTree(nodes, new Set())
    expect(rows.map((r) => r.rel)).toEqual(['INDEX.md', 'archive.zip', 'inbox', 'photo.png', 'projects', 'timeline.md'])
  })

  it('shows what is inside the folders that are open, and only those', () => {
    const rows = flattenTree(nodes, new Set(['projects']))
    expect(rows.map((r) => r.rel)).toEqual([
      'INDEX.md',
      'archive.zip',
      'inbox',
      'photo.png',
      'projects',
      'projects/2026',
      'timeline.md',
    ])
  })

  it('keeps a folder open all the way down while its parent is open', () => {
    const rows = flattenTree(nodes, new Set(['projects', 'projects/2026']))
    expect(rows.map((r) => r.rel)).toContain('projects/2026/q2-review.md')
  })

  it('refuses to open a folder that is not there rather than showing nothing at all', () => {
    // A rel typed into a test, or a folder deleted between two walks: the row still appears when its
    // parent opens, because `open` is a UI preference and must not be able to hide a file.
    const rows = flattenTree([entry('a.md'), entry('b.md')], new Set(['ghost']))
    expect(rows.map((r) => r.rel)).toEqual(['a.md', 'b.md'])
  })

  it('marks the four §9 states and puts the reason in the title', () => {
    const rows = flattenTree(
      [
        entry('embedded.md', { state: 'Embedded' }),
        entry('waiting-to-embed.md', { state: 'Indexed' }),
        entry('never-indexed.md', { state: 'Waiting' }),
        entry('refused.md', { state: { Refused: 'unreadable' } }),
      ],
      new Set(),
    )
    expect(rows.map((r) => [r.marker, r.title])).toEqual([
      ['·', 'embedded'],
      ['●', 'indexed · awaiting embedding'],
      ['○', 'not indexed yet'],
      ['!', 'refused · unreadable'],
    ])
  })

  it('says refused without inventing a reason when np gave none', () => {
    // §18.5: with diagnostics off, the marker reads *refused* and stops there.
    const [row] = flattenTree([entry('x.md', { state: { Refused: '' } })], new Set())
    expect(row?.marker).toBe('!')
    expect(row?.title).toBe('refused')
  })

  it('draws no marker where there is no index state to show, and greys what np wrote', () => {
    const rows = flattenTree(nodes, new Set())
    const byRel = new Map(rows.map((r) => [r.rel, r]))
    expect(byRel.get('photo.png')?.marker).toBe('')
    expect(byRel.get('inbox')?.marker).toBe('')
    // The tooltip used to read `generated by np`, which is a shrug; a person who has never seen one appear in
    // their folder needs the sentence, not the label.
    expect(byRel.get('INDEX.md')).toMatchObject({ marker: '', greyed: true, title: GENERATED_TITLE })
  })

  it('draws nothing for a marker from a newer build than this file knows', () => {
    // Better an unmarked row than a wrong one (§4).
    const [row] = flattenTree([entry('x.md', { state: 'VectorsPendingMigration' as never })], new Set())
    expect(row?.marker).toBe('')
    expect(row?.title).toBe('')
  })

  it('reports depth from the path, so nesting is visible without a second pass', () => {
    const rows = flattenTree(nodes, new Set(['projects', 'projects/2026']))
    const depth = new Map(rows.map((r) => [r.rel, r.depth]))
    expect(depth.get('projects')).toBe(0)
    expect(depth.get('projects/2026')).toBe(1)
    expect(depth.get('projects/2026/q2-review.md')).toBe(2)
  })

  it('says a folder is openable only when it has children', () => {
    const rows = flattenTree([entry('empty', { kind: 'Folder', state: null }), entry('note.md')], new Set())
    expect(rows.map((r) => r.hasChildren)).toEqual([false, false])
  })
})

describe('notesAwaitingIndex', () => {
  const note = (rel: string, state: NodeEntry['state']): NodeEntry => ({
    rel,
    kind: 'Note',
    size: 4,
    mtimeMs: 0,
    state,
  })

  it('counts the notes nobody has indexed yet', () => {
    // A vault opened for the first time is all of these, which is why the window says so instead of letting
    // search come back empty.
    expect(notesAwaitingIndex([note('a.md', 'Waiting'), note('b.md', null)])).toBe(2)
  })

  it('does not count work that was done or refused', () => {
    const nodes = [note('a.md', 'Indexed'), note('b.md', 'Embedded'), note('c.md', { Refused: 'too-large' })]
    expect(notesAwaitingIndex(nodes)).toBe(0)
  })

  it('ignores folders and np’s own catalogue', () => {
    const nodes: NodeEntry[] = [
      { rel: 'ideas', kind: 'Folder', size: 0, mtimeMs: 0, state: null },
      { rel: 'INDEX.md', kind: 'Generated', size: 900, mtimeMs: 0, state: null },
      note('a.md', 'Waiting'),
    ]
    expect(notesAwaitingIndex(nodes)).toBe(1)
  })
})

describe('the greyed catalogue row', () => {
  it('says whose file it is in a sentence', () => {
    const [row] = flattenTree([{ rel: 'INDEX.md', kind: 'Generated', size: 900, mtimeMs: 0, state: null }], new Set())
    expect(row?.greyed).toBe(true)
    expect(row?.title).toBe(GENERATED_TITLE)
    expect(row?.title).toContain('never edits it')
  })
})
