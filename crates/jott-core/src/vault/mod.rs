use std::io::Read;
use std::path::Path;

/// np's generated catalog header, byte for byte as `np-core`'s `catalog::HEADER` publishes it,
/// plus the CRLF spelling np treats as still being its own (line endings carry no identity).
const NP_INDEX_HEADER: [&[u8]; 2] = [
    b"# INDEX\n_generated by note-processor; do not edit_\n",
    b"# INDEX\r\n_generated by note-processor; do not edit_\r\n",
];

/// Whether this folder is a vault np has already indexed, judged the way §8.2 says to judge it:
/// by `INDEX.md` carrying np's fingerprint, not by a file merely wearing the name. A hand-written
/// `INDEX.md` is somebody's note, and warning about it would train someone to ignore the warning.
pub(crate) fn looks_like_np_vault(dir: &Path) -> bool {
    let Ok(mut file) = std::fs::File::open(dir.join("INDEX.md")) else { return false };
    // Read only what a header can be: an `INDEX.md` for four thousand notes is not worth opening
    // to answer one question about its first two lines.
    let longest = NP_INDEX_HEADER.iter().map(|h| h.len()).max().unwrap_or(0);
    let mut head = Vec::with_capacity(longest);
    if file.by_ref().take(longest as u64).read_to_end(&mut head).is_err() {
        return false;
    }
    NP_INDEX_HEADER.iter().any(|h| head.starts_with(h))
}
