#[test]
fn the_registry_holds_the_absolute_path_and_nothing_else_about_the_machine() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("appdata");
    let vault = vault_in(tmp.path(), "notes");
    VaultStore::new(root.clone()).register(&vault).unwrap();

    let registry = read_registry(&root);
    let entries = registry["vaults"].as_array().expect("a list of vaults");
    assert_eq!(entries.len(), 1);
    assert_eq!(entries[0]["path"].as_str(), Some(vault.to_str().expect("utf-8 path")));
    assert_eq!(entries[0]["consent"].as_str(), Some("undecided"));
    assert!(entries[0]["last_opened_ms"].is_number(), "a timestamp, not a sentence");
    // A file that leaves this machine must not name an origin or a user beyond the path (§14).
    let text = std::fs::read_to_string(root.join("vaults.json")).unwrap();
    assert!(!text.contains("http"), "{text}");
}

#[test]
fn a_saved_timestamp_is_the_one_that_goes_back_out() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("appdata");
    let vault = vault_in(tmp.path(), "notes");
    let store = VaultStore::new(root);
    store.register(&vault).unwrap();

    let opened = store.load()[0].last_opened;
    let age = SystemTime::now().duration_since(opened).expect("opened just now");
    assert!(age < Duration::from_secs(60), "last_opened is now, not an epoch zero: {age:?}");
}
