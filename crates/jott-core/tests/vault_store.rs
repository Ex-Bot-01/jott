#[test]
fn a_corrupt_registry_is_kept_and_the_app_opens_anyway() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("appdata");
    std::fs::create_dir_all(&root).unwrap();
    let registry = root.join("vaults.json");
    std::fs::write(&registry, b"{\"vaults\": [ {\"path\": ").expect("half a file");

    let store = VaultStore::new(root.clone());
    assert!(store.load().is_empty(), "a file we cannot read forgets, it does not fail startup");

    let kept: Vec<PathBuf> = std::fs::read_dir(&root)
        .unwrap()
        .flatten()
        .map(|e| e.path())
        .filter(|p| {
            p.file_name()
                .map(|n| n.to_string_lossy().starts_with("vaults.json.corrupt-"))
                .unwrap_or(false)
        })
        .collect();
    assert_eq!(kept.len(), 1, "the unreadable file is kept for whoever has to find the cause: {:?}", std::fs::read_dir(&root).map(|d| d.count()));
    assert_eq!(std::fs::read(&kept[0]).unwrap(), b"{\"vaults\": [ {\"path\": ");

    // And a fresh registry works from now on.
    let vault = vault_in(tmp.path(), "notes");
    store.register(&vault).unwrap();
    assert_eq!(store.load().len(), 1);
}

#[test]
fn the_registry_lands_in_the_os_data_dir() {
    let _turn = SERIAL.lock().unwrap_or_else(|e| e.into_inner());
    let tmp = tempfile::tempdir().unwrap();
    let xdg = tmp.path().join("xdg");
    let home = tmp.path().join("home");
    std::fs::create_dir_all(&home).unwrap();

    // XDG_DATA_HOME wins when it is set and absolute (§12's "the OS data dir", named the way the
    // platform names it).
    std::env::set_var("XDG_DATA_HOME", &xdg);
    std::env::set_var("HOME", &home);
    assert_eq!(app_data_dir().unwrap(), xdg.join("jott"));

    // Unset, and the XDG default applies.
    std::env::remove_var("XDG_DATA_HOME");
    assert_eq!(app_data_dir().unwrap(), home.join(".local/share/jott"));

    // A relative XDG_DATA_HOME is not a directory location; the base spec requires absolute, so
    // it is ignored rather than resolved against whatever the current folder happens to be.
    std::env::set_var("XDG_DATA_HOME", "relative/path");
    assert_eq!(app_data_dir().unwrap(), home.join(".local/share/jott"));

    // Nothing at all to root the path in is an error that names what is missing, not a guess.
    std::env::remove_var("XDG_DATA_HOME");
    std::env::remove_var("HOME");
    let err = app_data_dir().unwrap_err();
    assert!(err.to_string().contains("HOME"), "{err} names the variable to set");

    // A vault registered through that root puts one file there and nowhere else.
    std::env::set_var("XDG_DATA_HOME", &xdg);
    let vault = vault_in(tmp.path(), "notes");
    let store = jott_core::app_paths::app_data_dir()
        .map(VaultStore::new)
        .unwrap();
    store.register(&vault).unwrap();
    assert!(xdg.join("jott/vaults.json").is_file());
}

#[test]
fn registering_writes_nothing_inside_the_vault() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("appdata");
    let vault = vault_in(tmp.path(), "notes");
    std::fs::create_dir_all(vault.join("sub")).unwrap();
    let before = listing(&vault);

    let store = VaultStore::new(root);
    store.register(&vault).unwrap();
    store.set_consent(&vault, Consent::Declined).unwrap();
    store.load();

    assert_eq!(listing(&vault), before, "the vault holds the user's files and nothing else (§7)");
}

/// A tiny recursive listing, so this test does not depend on the walk Task 7 is writing.
fn listing(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    collect(dir, &mut out);
    out.sort();
    out
}

fn collect(dir: &Path, out: &mut Vec<PathBuf>) {
    out.push(dir.to_path_buf());
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(&path, out);
        } else {
            out.push(path);
        }
    }
}

#[test]
fn a_folder_inside_another_np_vault_warns_without_refusing() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("appdata");
    let parent = vault_in(tmp.path(), "notes");
    std::fs::write(parent.join("INDEX.md"), NP_HEADER).expect("np's own header");
    let sub = parent.join("sub");
    std::fs::create_dir_all(&sub).unwrap();

    let store = VaultStore::new(root);
    let warning = store.register(&sub).unwrap();
    assert_eq!(
        warning,
        Some(RegisterWarning::NestedVault { parent: parent.clone() }),
        "picking a subfolder of a vault is allowed and said out loud (§8.2)"
    );
    // Never a refusal: the folder is registered, because some people mean to do this.
    assert!(store.load().iter().any(|e| e.path == sub), "{:?}", store.load());
}

#[test]
fn np_header_with_windows_line_endings_is_still_nps() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("appdata");
    let parent = vault_in(tmp.path(), "notes");
    // Line endings carry no identity: a checkout or a sync client rewrites them without changing
    // whose catalog file it is.
    std::fs::write(parent.join("INDEX.md"), NP_HEADER.replace('\n', "\r\n")).unwrap();
    let sub = parent.join("sub");
    std::fs::create_dir_all(&sub).unwrap();

    let store = VaultStore::new(root);
    assert_eq!(
        store.register(&sub).unwrap(),
        Some(RegisterWarning::NestedVault { parent }),
        "a CRLF checkout of np's INDEX.md is the same vault"
    );
}

