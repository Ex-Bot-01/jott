//! The folder walk: what the tree shows, in what order, and what it is allowed to say about a
//! file it could not read. The two rules the Review Focus names: nothing vanishes from the tree,
//! and a state we did not measure is never invented.

use jott_core::vault::stamps::{StampState, Stamps};
use jott_core::vault::walk::{walk, walk_with, EntryKind, HashCache, TreeEntry};
use std::path::{Path, PathBuf};
use tempfile::TempDir;

/// A vault with the awkward files in it: a note in a subfolder, np's own catalog names, an image,
/// an attachment, a dot-folder, a dot-file, and a note whose bytes are not text.
struct Fixture {
    /// Held so the vault is cleaned up when the test finishes, and not before.
    _dir: TempDir,
    root: PathBuf,
}

impl Fixture {
    fn new() -> Fixture {
        let dir = tempfile::tempdir().expect("temp dir");
        let root = dir.path().to_path_buf();
        std::fs::create_dir_all(root.join("notes")).unwrap();
        std::fs::write(root.join("notes/a.md"), "# A\n").unwrap();
        std::fs::write(root.join("INDEX.md"), np_header()).unwrap();
        std::fs::write(root.join("INDEX-2a-z.md"), np_header()).unwrap();
        std::fs::write(root.join("img.png"), b"\x89PNG\r\n\x1a\n fake png").unwrap();
        std::fs::write(root.join("data.pdf"), b"%PDF-1.4 fake").unwrap();
        std::fs::create_dir_all(root.join(".git")).unwrap();
        std::fs::write(root.join(".git/config"), "[core]\n").unwrap();
        std::fs::write(root.join(".hidden.md"), "# hidden\n").unwrap();
        std::fs::write(root.join("mojibake.md"), [0x23, 0x20, 0xff, 0xfe, 0x0a]).unwrap();
        Fixture { _dir: dir, root }
    }

    fn path(&self) -> &Path {
        &self.root
    }

    fn tree(&self) -> Vec<TreeEntry> {
        let stamps = Stamps::with_root(self.root.join("appdata"), &self.root);
        walk(self.path(), &stamps).expect("a walk over a readable vault is not an error")
    }

    fn rels(&self) -> Vec<String> {
        self.tree().into_iter().map(|e| e.rel).collect()
    }

    fn entry(&self, rel: &str) -> TreeEntry {
        self.tree()
            .into_iter()
            .find(|e| e.rel == rel)
            .unwrap_or_else(|| panic!("{rel} is not in the tree: {:?}", self.rels()))
    }
}

fn np_header() -> String {
    "# INDEX\n_generated by note-processor; do not edit_\n".to_string()
}

/// A vault of our own, for tests that need their own files and nothing else. The caller holds the
/// `TempDir` so the folder is removed when the test ends.
fn vault_at(name: &str) -> (TempDir, PathBuf) {
    let tmp = tempfile::tempdir().expect("temp dir");
    let root = tmp.path().join(name);
    std::fs::create_dir_all(&root).unwrap();
    (tmp, root)
}

fn stamps_for(vault: &Path) -> Stamps {
    Stamps::with_root(vault.join("appdata"), vault)
}

fn tree_of(vault: &Path) -> Vec<TreeEntry> {
    walk(vault, &stamps_for(vault)).expect("the walk itself did not fail")
}

fn state_of(tree: &[TreeEntry], rel: &str) -> Option<StampState> {
    tree.iter()
        .find(|e| e.rel == rel)
        .unwrap_or_else(|| panic!("{rel} is missing from {:?}", tree.iter().map(|e| &e.rel).collect::<Vec<_>>()))
        .state
        .clone()
}

#[test]
fn the_tree_holds_folders_notes_images_and_attachments() {
    let f = Fixture::new();
    let tree = f.tree();
    let kinds: Vec<(String, EntryKind)> = tree.iter().map(|e| (e.rel.clone(), e.kind)).collect();

    for rel in ["notes", "notes/a.md", "INDEX.md", "img.png", "data.pdf"] {
        assert!(tree.iter().any(|e| e.rel == rel), "{rel} missing: {kinds:?}");
    }
    assert_eq!(f.entry("notes").kind, EntryKind::Folder);
    assert_eq!(f.entry("notes/a.md").kind, EntryKind::Note);
    assert_eq!(f.entry("img.png").kind, EntryKind::Image);
    assert_eq!(f.entry("data.pdf").kind, EntryKind::Attachment);

    let a = f.entry("notes/a.md");
    assert_eq!(a.size, 4, "the byte count the tree shows is the file's own (`# A\\n` is four bytes)");
    assert!(a.mtime <= std::time::SystemTime::now(), "mtime is real, not epoch zero");
}

#[test]
fn dot_files_and_dot_folders_are_not_offered_and_the_root_always_is() {
    let f = Fixture::new();
    let rels = f.rels();
    assert!(!rels.iter().any(|r| r.contains(".git")), "np does not index dot-paths either: {rels:?}");
    assert!(!rels.iter().any(|r| r == ".hidden.md"), "{rels:?}");

    // A vault whose own folder is hidden (`~/.notes`) is still a vault: the exclusion rule is about
    // what is inside it, matching np's own walk.
    let (_dir, hidden) = vault_at(".private-vault");
    std::fs::write(hidden.join("note.md"), "# N\n").unwrap();
    let tree = tree_of(&hidden);
    assert!(tree.iter().any(|e| e.rel == "note.md"), "a dot-named root still walks: {tree:?}");
}

#[test]
fn np_generated_names_are_marked_and_never_called_notes() {
    let f = Fixture::new();
    assert_eq!(f.entry("INDEX.md").kind, EntryKind::Generated);
    assert_eq!(f.entry("INDEX-2a-z.md").kind, EntryKind::Generated);

    // Exact case, root only: `index.md` is somebody's note, and a nested `INDEX-old.md` is one too
    // (np writes its catalogs at the root alone).
    let (_dir, dir) = vault_at("vault");
    std::fs::write(dir.join("index.md"), "# mine\n").unwrap();
    std::fs::create_dir_all(dir.join("notes")).unwrap();
    std::fs::write(dir.join("notes/INDEX-old.md"), "# mine too\n").unwrap();
    let tree = tree_of(&dir);
    assert_eq!(tree.iter().find(|e| e.rel == "index.md").unwrap().kind, EntryKind::Note);
    assert_eq!(
        tree.iter().find(|e| e.rel == "notes/INDEX-old.md").unwrap().kind,
        EntryKind::Note,
        "a nested INDEX-* is an ordinary note"
    );
}

#[test]
fn a_note_that_is_not_utf8_is_refused_and_the_walk_carries_on() {
    let f = Fixture::new();
    assert_eq!(
        state_of(&f.tree(), "mojibake.md"),
        Some(StampState::Refused("not-utf8".into())),
        "Jott's editor needs text; np's verdict is a different question and is not claimed here"
    );
    // The refusal is about that file, not about the walk.
    assert!(f.rels().contains(&"notes/a.md".to_string()));
}

// Linux-only because "unreadable" is made with a mode bit. Windows expresses this differently
// (§15 hands the platform-specific checks to a machine that has one), and what this test proves
// from the client side — one directory cannot fail the whole walk — stands either way.
#[cfg(unix)]
#[test]
fn an_unreadable_directory_is_one_refused_entry_and_not_an_error() {
    let (_dir, dir) = vault_at("vault");
    std::fs::write(dir.join("ok.md"), "# ok\n").unwrap();
    std::fs::create_dir_all(dir.join("locked")).unwrap();
    std::fs::write(dir.join("locked/hidden.md"), "# hidden\n").unwrap();
    if !make_unreadable(&dir.join("locked")) {
        panic!("this test needs to run as a user who can be denied a directory; chmod did not stick");
    }

    let tree = tree_of(&dir);
    assert_eq!(
        state_of(&tree, "locked"),
        Some(StampState::Refused("unreadable-dir".into())),
        "the folder says it could not be read instead of pretending to be empty"
    );
    // Its contents are unknown, not absent — but they are also not in the tree, because nothing
    // read them. What must not happen is the whole walk failing over one chmod.
    assert!(tree.iter().any(|e| e.rel == "ok.md"), "{tree:?}");

    restore_readable(&dir.join("locked"));
}

#[test]
fn a_stray_file_too_big_to_edit_is_refused_by_name_rather_than_by_hanging_the_tree() {
    let (_dir, dir) = vault_at("vault");
    // 33 MiB of one repeated character: the kind of file that lands in a notes folder from an
    // export, and is not a note anyone can read in a text editor.
    let big = dir.join("dump.md");
    let mut file = std::fs::File::create(&big).unwrap();
    use std::io::Write;
    for _ in 0..33 {
        file.write_all(&[b'a'; 1024 * 1024]).unwrap();
    }
    file.flush().unwrap();
    drop(file);

    let tree = tree_of(&dir);
    assert_eq!(
        state_of(&tree, "dump.md"),
        Some(StampState::Refused("too-large".into())),
        "named and shown, never hashed into the ground and never missing"
    );
}

#[test]
fn stamps_show_through_the_tree_and_generated_files_get_no_marker() {
    let (_dir, dir) = vault_at("vault");
    let note = dir.join("a.md");
    std::fs::write(&note, "# A\n").unwrap();
    std::fs::write(dir.join("b.md"), "# B\n").unwrap();
    std::fs::write(dir.join("INDEX.md"), np_header()).unwrap();
    std::fs::write(dir.join("pic.png"), b"not really a png").unwrap();

    let mut stamps = stamps_for(&dir);
    let hash_a = jott_core::hashes::sha256_file(&note).unwrap();
    stamps.mark_embedded("a.md", &hash_a);

    let tree = walk(&dir, &stamps).unwrap();
    assert_eq!(state_of(&tree, "a.md"), Some(StampState::Embedded));
    assert_eq!(state_of(&tree, "b.md"), Some(StampState::Waiting), "never seen is waiting, not clean");
    assert_eq!(state_of(&tree, "INDEX.md"), None, "np's own file has no marker to show (§9)");
    assert_eq!(state_of(&tree, "pic.png"), None, "no image rows exist in an np without vision");

    // A changed byte changes the answer: the stamp is about these bytes, not about the path.
    std::fs::write(&note, "# A edited\n").unwrap();
    let tree = walk(&dir, &stamps).unwrap();
    assert_eq!(state_of(&tree, "a.md"), Some(StampState::Waiting));
}

#[test]
fn a_processed_folder_is_shown_and_promises_nothing() {
    let (_dir, dir) = vault_at("vault");
    std::fs::create_dir_all(dir.join("processed")).unwrap();
    std::fs::write(dir.join("processed/done.md"), "# done\n").unwrap();
    std::fs::write(dir.join("live.md"), "# live\n").unwrap();

    // np's own walk excludes `processed` at every depth (measured in 0.3.1: `is_excluded`), so a
    // "waiting to embed" marker on those notes would be a promise the index will never keep (§4).
    let tree = tree_of(&dir);
    assert_eq!(state_of(&tree, "processed/done.md"), None, "visible, and claiming nothing");
    assert_eq!(state_of(&tree, "live.md"), Some(StampState::Waiting), "the rest of the vault is still honest");
}

#[test]
fn rel_paths_use_forward_slashes_at_every_depth() {
    let (_dir, dir) = vault_at("vault");
    std::fs::create_dir_all(dir.join("projects/2026/q3")).unwrap();
    std::fs::write(dir.join("projects/2026/q3/review.md"), "# R\n").unwrap();

    let tree = tree_of(&dir);
    let rels: Vec<&str> = tree.iter().map(|e| e.rel.as_str()).collect();
    assert!(rels.contains(&"projects"), "{rels:?}");
    assert!(rels.contains(&"projects/2026"), "{rels:?}");
    assert!(rels.contains(&"projects/2026/q3/review.md"), "{rels:?}");
    assert!(rels.iter().all(|r| !r.contains('\\')), "the tree's keys are np's rel spelling everywhere: {rels:?}");
}

#[test]
fn the_order_is_by_rel_bytes_so_two_platforms_agree() {
    let (_dir, dir) = vault_at("vault");
    for rel in ["b.md", "B.md", "a/z.md", "a.md", "notes/deep/x.md"] {
        let path = dir.join(rel);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).unwrap();
        }
        std::fs::write(path, "# x\n").unwrap();
    }

    let rels = tree_of(&dir).into_iter().map(|e| e.rel).collect::<Vec<_>>();
    let mut sorted = rels.clone();
    sorted.sort_unstable();
    assert_eq!(rels, sorted, "sorted by the bytes of rel: {rels:?}");
    // Byte order, not case-folded and not locale-collated: uppercase sorts before lowercase, which
    // is what a Windows machine and a Linux machine both get.
    assert_eq!(rels.first().map(String::as_str), Some("B.md"), "{rels:?}");
}

#[test]
fn walking_a_folder_that_is_not_there_says_which_one() {
    let stamps = stamps_for(Path::new("/definitely/not/here"));
    let err = walk(Path::new("/definitely/not/here"), &stamps).unwrap_err();
    assert!(err.to_string().contains("/definitely/not/here"), "{err} names the folder");
}

#[cfg(unix)]
fn make_unreadable(dir: &Path) -> bool {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o000)).unwrap();
    // Root reads it anyway, and then the test would prove nothing.
    std::fs::read_dir(dir).is_err()
}

#[cfg(unix)]
fn restore_readable(dir: &Path) {
    use std::os::unix::fs::PermissionsExt;
    let _ = std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o755));
}



// ---- the digest cache, which is why re-listing a folder costs nothing it already looked at ----

/// A listing walks the folder and hashes every note in it. On a 2,000-note vault that measured ~40 ms in a
/// release build — and the window lists again after every save, rename and ingest event, so the same unchanged
/// bytes were hashed over and over within one second of each other. The cache is per run of the app: it trusts
/// `(size, mtime)` to say "these are the bytes I already read", which is a cache's business, not a stamp's —
/// §18.13 refused the same trust for *unsaved text*, where being wrong costs someone their words. Here the
/// worst a lie can do is hold one dot at the wrong state until the file genuinely moves again.
#[test]
fn a_note_that_has_not_moved_is_not_read_again() {
    let dir = TempDir::new().unwrap();
    put(dir.path(), "a.md", b"# A\n");
    put(dir.path(), "b.md", b"# B\n");
    let stamps = stamps_for(dir.path());

    let cache = HashCache::new();
    walk_with(dir.path(), &stamps, &cache).unwrap();
    assert_eq!(cache.stats(), (0, 2), "the first listing has to read both notes");

    walk_with(dir.path(), &stamps, &cache).unwrap();
    assert_eq!(cache.stats(), (2, 2), "the second one reads neither");
}

/// The other half of the bargain: bytes that changed are hashed again. Same length on purpose — a cache keyed
/// on size alone would pass the test above and fail this one.
#[test]
fn a_note_that_moved_is_hashed_again() {
    let dir = TempDir::new().unwrap();
    put(dir.path(), "a.md", b"# A\n");
    put(dir.path(), "b.md", b"# B\n");
    let stamps = stamps_for(dir.path());

    let cache = HashCache::new();
    walk_with(dir.path(), &stamps, &cache).unwrap();

    // Same byte count, different content. `set_modified` rather than trusting the clock: two writes inside one
    // timestamp tick are exactly how §18.13's mirror got fooled once already.
    put(dir.path(), "a.md", b"# Z\n");
    let moved = std::fs::metadata(dir.path().join("a.md"))
        .unwrap()
        .modified()
        .unwrap()
        + std::time::Duration::from_secs(1);
    std::fs::File::options()
        .write(true)
        .open(dir.path().join("a.md"))
        .unwrap()
        .set_modified(moved)
        .unwrap();

    let entries = walk_with(dir.path(), &stamps, &cache).unwrap();
    assert_eq!(cache.stats(), (1, 3), "one note reused, the moved one read again");
    let a = entries.iter().find(|e| e.rel == "a.md").unwrap();
    assert_eq!(a.state, Some(StampState::Waiting), "and its state is judged on the new bytes");
}

/// A digest is a digest: whatever path the bytes took to get here — read into memory or streamed through the
/// hasher — it names the same file. This is the fixture np's own index keys on (§18.8).
#[test]
fn the_cached_digest_is_the_same_number_as_streaming_the_file() {
    let dir = TempDir::new().unwrap();
    // 300 KB, so a streamed read and a buffered one are not accidentally the same code path at 64 KiB.
    let body = "x".repeat(300 * 1024);
    put(dir.path(), "big.md", format!("# Big\n\n{body}\n").as_bytes());
    let stamps = stamps_for(dir.path());

    let cache = HashCache::new();
    let entries = walk_with(dir.path(), &stamps, &cache).unwrap();
    assert_eq!(entries.len(), 1);
    let expected = jott_core::hashes::sha256_file(&dir.path().join("big.md")).unwrap();
    // Nothing was indexed, so the state is `Waiting` either way; what this pins is that the walk's own digest
    // — the one a stamp is compared against — matches the streamed hash exactly.
    let stamps = {
        let mut fresh = stamps_for(dir.path());
        fresh.mark_indexed("big.md", &expected);
        fresh
    };
    let entries = walk_with(dir.path(), &stamps, &cache).unwrap();
    assert_eq!(
        entries[0].state,
        Some(StampState::Indexed),
        "the digest the walk produced is the one a stamp matches: {expected}"
    );
}

fn put(root: &Path, rel: &str, bytes: &[u8]) {
    std::fs::create_dir_all(root.join(rel).parent().unwrap()).ok();
    std::fs::write(root.join(rel), bytes).expect("the test wrote this");
}

/// The shared cache is keyed by the file, not by the tree row. Two vaults in one run both have an `a.md`, and
/// a note copied between them can share a byte count *and* an mtime — a key of `rel` alone would answer one
/// vault's digest for the other, which is a wrong marker on someone's real notes.
#[test]
fn two_vaults_with_a_note_of_the_same_name_are_not_the_same_note() {
    let one = TempDir::new().unwrap();
    let two = TempDir::new().unwrap();
    put(one.path(), "a.md", b"# A\n");
    put(two.path(), "a.md", b"# B\n");
    // Identical size, and the timestamp forced to match: the only difference left is the bytes.
    let stamp = std::fs::metadata(one.path().join("a.md")).unwrap().modified().unwrap();
    std::fs::File::options()
        .write(true)
        .open(two.path().join("a.md"))
        .unwrap()
        .set_modified(stamp)
        .unwrap();

    let cache = HashCache::new();
    let mut stamps = stamps_for(one.path());
    stamps.mark_indexed("a.md", &jott_core::hashes::sha256_file(&one.path().join("a.md")).unwrap());
    let other = stamps_for(two.path());

    let entries = walk_with(one.path(), &stamps, &cache).unwrap();
    assert_eq!(state_of(&entries, "a.md"), Some(StampState::Indexed));

    let entries = walk_with(two.path(), &other, &cache).unwrap();
    assert_eq!(
        state_of(&entries, "a.md"),
        Some(StampState::Waiting),
        "the second vault's a.md was judged on its own bytes"
    );
    assert_eq!(cache.stats().1, 2, "both were read; neither borrowed the other's digest");
}
